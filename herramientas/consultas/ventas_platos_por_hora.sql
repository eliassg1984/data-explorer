/*
  VENTA DE PLATOS POR HORA, CON LOS PLATOS QUE VAN DENTRO DE LOS COMBOS

  Una fila por cada cosa que salió de la cocina o la barra, en tres ORIGEN:
    SUELTO           el plato pedido solo (DDOCUMENTO, linea sin combinación)
    COMBO            la linea del combo como se cobró (DDOCUMENTO, lCombinacion = 1)
    DENTRO DE COMBO  cada plato elegido dentro de ese combo (CPEDIDO)

  Dos cantidades, para que la tabla dinamica no cuente nada dos veces:
    CANTIDAD PLATOS   = SUELTO + DENTRO DE COMBO  (cuantos se sirvieron; 0 en la linea COMBO)
    CANTIDAD VENDIDA  = SUELTO + COMBO            (lo que se cobró; 0 dentro del combo)
  El dinero (NETO, VENTA) va sólo en SUELTO y COMBO: el combo se cobra entero y
  el POS no reparte su precio entre los platos.

  CLASE: VENTA / CORTESIA / ANULADO / ANULADO POR NOTA CREDITO. Para contar lo
  vendido, filtrar CLASE = VENTA (las notas de crédito anulan el documento
  entero: el canje de boleta por factura saldría dos veces).

  HORA PEDIDO = cuando se abrió la mesa; HORA ITEM = cuando se pidió ese plato
  (el postre llega una o dos horas después). Si el POS no guardó la hora del
  item, HORA ITEM toma la del pedido.

  DIA SEMANA, FECHA PEDIDO y MEDIA HORA PEDIDO salen de la hora del pedido.
  MEDIA HORA PEDIDO parte la hora en dos ('17:00' = 17:00 a 17:29, '17:30' =
  17:30 a 17:59): de 5:30 pm a 10 pm son los tramos '17:30' a '21:30'.
  N DIA SEMANA (1 = Lunes ... 7 = Domingo) sirve para ordenar los dias.
  El dia se calcula sin DATENAME, asi no depende del idioma del servidor.

  Sin pagos: una fila por forma de pago duplicaria las cantidades.
*/
SELECT
        'SUELTO O COMBO' AS 'NIVEL',
        (CASE WHEN INFOREST.DBO.DPEDIDO.lCombinacion = 1 THEN 'COMBO' ELSE 'SUELTO' END) AS 'ORIGEN',
        (CASE
            WHEN INFOREST.DBO.MDOCUMENTO.tEstadoDocumento = '04' THEN 'ANULADO'
            WHEN INFOREST.DBO.MNOTACREDITO.tNotaCredito IS NOT NULL THEN 'ANULADO POR NOTA CREDITO'
            WHEN INFOREST.DBO.TTIPODOCUMENTO.tDescripcion LIKE '%CORTESIA%' THEN 'CORTESIA'
            WHEN INFOREST.DBO.TTIPODOCUMENTO.tDescripcion LIKE '%CONSUMO%'
              OR INFOREST.DBO.TTIPODOCUMENTO.tDescripcion LIKE '%SALIDA%' THEN 'NO VENTA'
            ELSE 'VENTA'
        END) AS 'CLASE',
        INFOREST.DBO.MDOCUMENTO.fRegistro AS 'FEC REG DOCUMENTO',
        INFOREST.DBO.MDOCUMENTO.fDiaContable AS 'DIA CONTABLE',
        INFOREST.DBO.MPEDIDO.fRegistro AS 'FECHA HORA PEDIDO',
        DATEPART(hour, INFOREST.DBO.MPEDIDO.fRegistro) AS 'HORA PEDIDO',
        ISNULL(INFOREST.DBO.DPEDIDO.fregistro, INFOREST.DBO.MPEDIDO.fRegistro) AS 'FECHA HORA ITEM',
        DATEPART(hour, ISNULL(INFOREST.DBO.DPEDIDO.fregistro, INFOREST.DBO.MPEDIDO.fRegistro)) AS 'HORA ITEM',
        CAST(INFOREST.DBO.MPEDIDO.fRegistro AS date) AS 'FECHA PEDIDO',
        (CASE DATEDIFF(day, '19000101', INFOREST.DBO.MPEDIDO.fRegistro) % 7
            WHEN 0 THEN 'Lunes' WHEN 1 THEN 'Martes' WHEN 2 THEN 'Miercoles' WHEN 3 THEN 'Jueves'
            WHEN 4 THEN 'Viernes' WHEN 5 THEN 'Sabado' WHEN 6 THEN 'Domingo'
        END) AS 'DIA SEMANA',
        (DATEDIFF(day, '19000101', INFOREST.DBO.MPEDIDO.fRegistro) % 7) + 1 AS 'N DIA SEMANA',
        (RIGHT('0' + CAST(DATEPART(hour, INFOREST.DBO.MPEDIDO.fRegistro) AS varchar(2)), 2) + ':'
         + (CASE WHEN DATEPART(minute, INFOREST.DBO.MPEDIDO.fRegistro) < 30 THEN '00' ELSE '30' END)) AS 'MEDIA HORA PEDIDO',
        (CASE
            WHEN INFOREST.DBO.MPEDIDO.fRegistro IS NULL THEN NULL
            WHEN CAST(INFOREST.DBO.MPEDIDO.fRegistro AS TIME) >= '07:00:00'
             AND CAST(INFOREST.DBO.MPEDIDO.fRegistro AS TIME) <  '12:00:00' THEN 'DESAYUNO'
            WHEN CAST(INFOREST.DBO.MPEDIDO.fRegistro AS TIME) >= '12:00:00'
             AND CAST(INFOREST.DBO.MPEDIDO.fRegistro AS TIME) <  '17:30:00' THEN 'ALMUERZO'
            ELSE 'CENA'
        END) AS 'SERVICIO',
        INFOREST.DBO.TTIPODOCUMENTO.tDescripcion AS 'TIPO DOC',
        INFOREST.DBO.MDOCUMENTO.tDocumento AS 'NUMERO DOCUMENTO',
        INFOREST.DBO.DDOCUMENTO.tCodigoPedido AS 'CODIGO PEDIDO',
        INFOREST.DBO.DDOCUMENTO.tItem AS 'ITEM',
        NULL AS 'ITEM COMBO',
        INFOREST.DBO.TCANALVENTA.tDetallado AS 'CANAL VENTA',
        INFOREST.DBO.DDOCUMENTO.tCodigoProducto AS 'COD PRODUCTO',
        INFOREST.DBO.TPRODUCTO.tDetallado AS 'PRODUCTO',
        INFOREST.DBO.TGRUPO.tDetallado AS 'GRUPO',
        INFOREST.DBO.TSUBGRUPO.tDetallado AS 'SUB GRUPO',
        (CASE WHEN INFOREST.DBO.DPEDIDO.lCombinacion = 1 THEN INFOREST.DBO.DDOCUMENTO.tCodigoProducto END) AS 'COD COMBO',
        (CASE WHEN INFOREST.DBO.DPEDIDO.lCombinacion = 1 THEN INFOREST.DBO.TPRODUCTO.tDetallado END) AS 'COMBO',
        (CASE WHEN INFOREST.DBO.DPEDIDO.lCombinacion = 1 THEN 0 ELSE INFOREST.DBO.DDOCUMENTO.nCantidad END) AS 'CANTIDAD PLATOS',
        INFOREST.DBO.DDOCUMENTO.nCantidad AS 'CANTIDAD VENDIDA',
        (INFOREST.DBO.DDOCUMENTO.nPrecioNeto * INFOREST.DBO.DDOCUMENTO.nCantidad) AS 'NETO',
        INFOREST.DBO.DDOCUMENTO.nVenta AS 'VENTA'
FROM INFOREST.DBO.DDOCUMENTO
        INNER JOIN INFOREST.DBO.MDOCUMENTO ON INFOREST.DBO.DDOCUMENTO.tDocumento = INFOREST.DBO.MDOCUMENTO.tDocumento
        LEFT JOIN INFOREST.DBO.TTIPODOCUMENTO ON INFOREST.DBO.MDOCUMENTO.tTipoDocumento = INFOREST.DBO.TTIPODOCUMENTO.tCodigoTipoDocumento
        LEFT JOIN INFOREST.DBO.MNOTACREDITO ON INFOREST.DBO.MDOCUMENTO.tDocumento = INFOREST.DBO.MNOTACREDITO.tDocumento
        LEFT JOIN INFOREST.DBO.MPEDIDO ON INFOREST.DBO.DDOCUMENTO.tCodigoPedido = INFOREST.DBO.MPEDIDO.tCodigoPedido
        LEFT JOIN INFOREST.DBO.DPEDIDO
            ON INFOREST.DBO.DDOCUMENTO.tCodigoPedido = INFOREST.DBO.DPEDIDO.tCodigoPedido
           AND INFOREST.DBO.DDOCUMENTO.tItem = INFOREST.DBO.DPEDIDO.tItem
        LEFT JOIN INFOREST.DBO.TCANALVENTA ON INFOREST.DBO.MPEDIDO.tTipoPedido = INFOREST.DBO.TCANALVENTA.tCodigoCanalVenta
        LEFT JOIN INFOREST.DBO.TPRODUCTO ON INFOREST.DBO.DDOCUMENTO.tCodigoProducto = INFOREST.DBO.TPRODUCTO.tCodigoProducto
        LEFT JOIN INFOREST.DBO.TGRUPO ON INFOREST.DBO.TPRODUCTO.tGrupo = INFOREST.DBO.TGRUPO.tCodigoGrupo
        LEFT JOIN INFOREST.DBO.TSUBGRUPO ON INFOREST.DBO.TPRODUCTO.tSubGrupo = INFOREST.DBO.TSUBGRUPO.tCodigoSubgrupo
WHERE INFOREST.DBO.MDOCUMENTO.fRegistro >= '2025-01-01 00:00:00' AND INFOREST.DBO.MDOCUMENTO.fRegistro < '2028-01-01 00:00:00'

